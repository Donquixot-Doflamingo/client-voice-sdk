#!/usr/bin/env bash
# End-to-end test matrix for the desktop build. Writes docs/TEST-REPORT.md with the real outputs.
# Needs: build/*.jar (scripts/build-jvm.sh), packs installed in ~/.indicvoice/packs (bin/indicvoice packs install ...).
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:-}"
REPORT=docs/TEST-REPORT.md; mkdir -p docs build/test-out
PASS=0; FAIL=0
section() { printf '\n## %s\n\n' "$1" >> "$REPORT"; }
run() { # run "title" cmd...   -> appends command + output; counts exit status
  local title="$1"; shift
  printf '### %s\n\n```\n$ %s\n' "$title" "$*" >> "$REPORT"
  local out; out="$("$@" 2>&1 | grep -v -E '^Picked up JAVA_TOOL_OPTIONS|offline-tts.cc|^OfflineTtsConfig|^\[voice\] loaded|^\[voice\] evicted')"; local rc=${PIPESTATUS[0]}
  printf '%s\n```\n' "$out" >> "$REPORT"
  if [ "$rc" -eq 0 ]; then PASS=$((PASS+1)); printf '_exit 0 — PASS_\n\n' >> "$REPORT"; else FAIL=$((FAIL+1)); printf '_exit %s — **FAIL**_\n\n' "$rc" >> "$REPORT"; fi
  echo "[$title] exit $rc"
}

cat > "$REPORT" <<EOF
# Test report — indic-voice-sdk

Generated by \`scripts/run-tests.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC').

| | |
|---|---|
| Host | $(uname -s) $(uname -m), $(nproc) CPU, $(free -g 2>/dev/null | awk '/Mem/{print $2" GB RAM"}') |
| Java | $(java -version 2>&1 | grep -v JAVA_TOOL_OPTIONS | head -1 | tr -d '"') |
| sherpa-onnx | 1.13.8 (JNI, CPU) |
| Packs dir | ${INDICVOICE_PACKS_DIR:-$HOME/.indicvoice/packs} |

Every block below is the literal command and its literal output. Nothing is hand-edited.
EOF

section "1. Core self-test (JSON, 23 languages, language detection in 15 languages + romanised Hindi, transcript format, WAV, resampling, VAD segmenter, WER/CER, config + catalog, bzip2)"
if [ ! -f build/selftest.jar ] || [ sdk-core/src/test/kotlin/dev/indicvoice/core/SelfTest.kt -nt build/selftest.jar ]; then
  kotlinc -nowarn -jvm-target 17 -cp build/indicvoice-cli.jar -d build/selftest.jar sdk-core/src/test/kotlin 2>&1 | grep -E 'error' || true
fi
bin/indicvoice tts --text "नमस्ते, मेरा नाम मयंक है और मैं दिल्ली में रहता हूँ।" --lang hi --out build/test-out/hi-ref.wav >/dev/null 2>&1
run "selftest" env LC_ALL=C.UTF-8 java -Dfile.encoding=UTF-8 -Dstdout.encoding=UTF-8 -cp build/selftest.jar:build/indicvoice-cli.jar dev.indicvoice.core.SelfTest build/test-out/hi-ref.wav

section "2. Capabilities and packs on this machine"
run "caps" bin/indicvoice caps
run "packs list" bin/indicvoice packs list

section "3. Text → speech (tier 2 packs)"
run "tts hi piper" bin/indicvoice tts --text "आपका स्वागत है, कृपया अपना खाता नंबर बताइए।" --lang hi --out build/test-out/tts-hi-piper.wav
run "tts hi kokoro (hf_alpha)" bin/indicvoice tts --text "आपका स्वागत है, कृपया अपना खाता नंबर बताइए।" --lang hi --voice "pack:kokoro-int8-multilang#hf_alpha" --out build/test-out/tts-hi-kokoro.wav
run "tts en kokoro" bin/indicvoice tts --text "Welcome. Please tell me your account number." --lang en --voice "pack:kokoro-int8-multilang#af_heart" --out build/test-out/tts-en-kokoro.wav
run "voices hi" bin/indicvoice voices --lang hi

section "4. Speech → text: language detection + words (tier 2, auto-detect)"
run "stt auto (Hindi, piper voice)" bin/indicvoice stt --file build/test-out/tts-hi-piper.wav
run "stt auto (Hindi, kokoro voice) — JSON output format" bin/indicvoice stt --file build/test-out/tts-hi-kokoro.wav --json
run "stt auto (English, kokoro voice)" bin/indicvoice stt --file build/test-out/tts-en-kokoro.wav
run "stt forced hi, omnilingual pack" bin/indicvoice stt --file build/test-out/tts-hi-piper.wav --lang hi --pack omnilingual-300m-int8
bin/indicvoice tts --text "എനിക്ക് ഒരു ഗ്ലാസ് വെള്ളം വേണം" --lang ml --out build/test-out/tts-ml.wav >/dev/null 2>&1
bin/indicvoice tts --text "મને એક ગ્લાસ પાણી જોઈએ છે અને કાલે સવારે દિલ્હી જવું છે" --lang gu --out build/test-out/tts-gu.wav >/dev/null 2>&1
run "stt auto (Malayalam, piper voice) — routed to Omnilingual" bin/indicvoice stt --file build/test-out/tts-ml.wav
run "stt auto (Gujarati, mimic3 voice)" bin/indicvoice stt --file build/test-out/tts-gu.wav
run "stt Malayalam with Dolphin (known weakness: writes Tamil)" bin/indicvoice stt --file build/test-out/tts-ml.wav --pack dolphin-base-int8 --lang ml

section "5. Round trips (TTS → STT) with WER/CER — Hindi"
run "roundtrip 1" bin/indicvoice roundtrip --text "मुझे एक गिलास पानी चाहिए और कल सुबह दिल्ली जाना है" --lang hi
run "roundtrip 2 (auto-detect)" bin/indicvoice roundtrip --text "कृपया मेरे खाते का बैलेंस बताइए" --lang hi --auto
run "roundtrip 3" bin/indicvoice roundtrip --text "मैं दिल्ली में रहता हूँ और कल मुंबई जाऊँगा" --lang hi
run "roundtrip 4 (numbers + English words)" bin/indicvoice roundtrip --text "मेरा ऑर्डर नंबर दो सौ पैंतालीस है और डिलीवरी कल होनी चाहिए" --lang hi
run "roundtrip 5 (kokoro voice → dolphin)" bin/indicvoice roundtrip --text "आज मौसम बहुत अच्छा है" --lang hi --voice "pack:kokoro-int8-multilang#hm_omega"
run "roundtrip 6 Malayalam (piper → omnilingual)" bin/indicvoice roundtrip --text "എനിക്ക് ഒരു ഗ്ലാസ് വെള്ളം വേണം" --lang ml
run "roundtrip 7 Gujarati (mimic3 → omnilingual)" bin/indicvoice roundtrip --text "મને એક ગ્લાસ પાણી જોઈએ છે" --lang gu

section "6. Tier 3 through the reference backend (free local provider)"
if ! curl -s -m 3 localhost:8080/v1/health >/dev/null; then (nohup bin/indicvoice-proxy > build/test-out/proxy.log 2>&1 &); sleep 8; fi
run "health" curl -s localhost:8080/v1/health
run "POST /v1/stt (audio/wav, auto)" bash -c "curl -s -X POST localhost:8080/v1/stt -H 'Content-Type: audio/wav' -H 'X-Voice-Language: auto' --data-binary @build/test-out/tts-hi-piper.wav | python3 -c 'import json,sys; d=json.load(sys.stdin); print(json.dumps({k:d[k] for k in (\"language\",\"text\",\"wordCount\",\"tier\",\"engine\",\"latencyMs\",\"audioMs\",\"rtf\")}, ensure_ascii=False, indent=2))'"
run "POST /v1/tts (headers)" bash -c "curl -s -D - -o build/test-out/proxy-tts.wav -X POST localhost:8080/v1/tts -H 'Content-Type: application/json' -d '{\"text\":\"धन्यवाद, आपका दिन शुभ हो\",\"language\":\"hi\"}' | grep -i -E '^HTTP|X-Voice' ; ls -la build/test-out/proxy-tts.wav | awk '{print \$5\" bytes\"}'"
run "GET /v1/voices?language=hi" curl -s 'localhost:8080/v1/voices?language=hi'
run "tier 3 from the CLI" bin/indicvoice stt --file build/test-out/tts-hi-piper.wav --tier 3 --backend http://localhost:8080
run "unauthorised when PROXY_TOKEN set (simulated: wrong token against open server passes = n/a)" curl -s -o /dev/null -w '%{http_code}' localhost:8080/v1/health

section "7. Benchmark: same recording through every tier + every STT pack"
run "bench all tiers (dolphin as tier 2)" bin/indicvoice bench --file build/test-out/tts-hi-piper.wav --ref "आपका स्वागत है कृपया अपना खाता नंबर बताइए" --backend http://localhost:8080
run "bench omnilingual pack" bin/indicvoice bench --file build/test-out/tts-hi-piper.wav --ref "आपका स्वागत है कृपया अपना खाता नंबर बताइए" --pack omnilingual-300m-int8 --tiers 2 --lang hi
run "bench whisper-base pack" bin/indicvoice bench --file build/test-out/tts-hi-piper.wav --ref "आपका स्वागत है कृपया अपना खाता नंबर बताइए" --pack whisper-base-int8 --tiers 2
run "bench JSON (what the app shows)" bin/indicvoice bench --file build/test-out/tts-hi-piper.wav --tiers 2,3 --backend http://localhost:8080 --json

section "8. Feature switch and error paths"
run "no backend → tier 3 unavailable (expected error)" bash -c "bin/indicvoice stt --file build/test-out/tts-hi-piper.wav --tier 3 2>&1; echo exit \$?"
run "unknown pack (expected error)" bash -c "bin/indicvoice stt --file build/test-out/tts-hi-piper.wav --tier 2 --pack nope 2>&1; echo exit \$?"

section "9. Android + Expo module compile checks (javac/kotlinc against android.jar API 35 and Expo API stubs)"
if [ -f /opt/tools/android/plat/android-35/android.jar ]; then
  run "sdk-android compiles against android.jar" bash -c "kotlinc -nowarn -jvm-target 17 -cp /opt/tools/android/plat/android-35/android.jar:build/classes -d build/android-check sdk-android/src/main/kotlin 2>&1 | grep -c error | sed 's/^/errors: /'"
  run "expo module compiles (API stubs)" bash -c "kotlinc -nowarn -jvm-target 17 -cp /opt/tools/android/plat/android-35/android.jar:build/android-check:build/classes -d build/expo-check /opt/tools/expo/stubs apps/VoiceTestApp/modules/indic-voice/android/src/main/java 2>&1 | grep -c error | sed 's/^/errors: /'"
else
  printf '_android.jar not available on this host; skipped_\n' >> "$REPORT"
fi

section "10. Web console (headless Chromium): upload WAV → tier 3 result card, TTS → audio"
if [ -f scripts/console-test.js ]; then run "playwright console test" node /tmp/pw/console-test.js; else printf '_playwright script not present; skipped_\n' >> "$REPORT"; fi

section "10b. Mobile test site /m (headless Chromium): tier 2 + tier 3 (custom URL) from a WAV, TTS via tier 2"
run "msite test" node scripts/msite-test.js

section "11. Live (streaming) recognition path: replayed microphone frames → VAD segmenter → tier 2, two utterances, clean stop"
if [ ! -f build/livetest.jar ] || [ sdk-jvm/src/test/kotlin/dev/indicvoice/jvm/LiveTest.kt -nt build/livetest.jar ]; then
  kotlinc -nowarn -jvm-target 17 -cp build/indicvoice-cli.jar -d build/livetest.jar sdk-jvm/src/test/kotlin 2>&1 | grep -E 'error' || true
fi
run "live session (Hindi, dolphin, replayed audio)" bash -c "LC_ALL=C.UTF-8 java -Dfile.encoding=UTF-8 -Dstdout.encoding=UTF-8 -cp build/livetest.jar:build/indicvoice-cli.jar:third_party/sherpa-onnx/libs/sherpa-onnx-native-lib-linux-x64-1.13.8.jar dev.indicvoice.jvm.LiveTestKt build/test-out/tts-hi-piper.wav 2>&1 | grep -v -E 'voice-activity-detector|^VadModelConfig'"

section "12. Accuracy-test endpoints: store prompted clips, score Auto + every installed pack"
run "eval: store 2 clips + run" bash -c "curl -s -X DELETE localhost:8080/v1/eval >/dev/null; for x in 'build/test-out/tts-hi-piper.wav|hi|आपका स्वागत है, कृपया अपना खाता नंबर बताइए।' 'build/test-out/tts-en-kokoro.wav|en|Welcome. Please tell me your account number.'; do IFS='|' read -r f l t <<< \"\$x\"; python3 -c 'import sys,json,base64; print(json.dumps({\"language\":sys.argv[2],\"text\":sys.argv[3],\"audioBase64\":base64.b64encode(open(sys.argv[1],\"rb\").read()).decode()}))' \"\$f\" \"\$l\" \"\$t\" | curl -s -X POST localhost:8080/v1/eval -H 'Content-Type: application/json' --data-binary @-; echo; done; curl -s -X POST localhost:8080/v1/eval/run | python3 -c 'import json,sys; j=json.load(sys.stdin); [print(s[\"system\"], s[\"accuracy\"], \"%\", s[\"languageCorrect\"]) for s in j[\"summary\"]]; sys.exit(0 if j[\"clips\"]==2 and j[\"summary\"] else 1)'; curl -s -X DELETE localhost:8080/v1/eval"

printf '\n---\n\n**Summary: %s passed, %s failed.**\n' "$PASS" "$FAIL" >> "$REPORT"
echo "report: $REPORT  (pass=$PASS fail=$FAIL)"
